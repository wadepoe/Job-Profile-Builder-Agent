"""
Profile output delivery tool.
Delivers an approved job profile in the user's chosen mode:
  1. API write to SuccessFactors
  2. CSV export for bulk upload
  3. Formatted document draft
"""

import csv
import io
import json
import logging
from typing import Any

from langchain_core.tools import tool

logger = logging.getLogger(__name__)


def _build_csv(profile: dict[str, Any]) -> str:
    """Format a profile as a SuccessFactors Job Profile Builder import CSV."""
    output = io.StringIO()
    writer = csv.writer(output, quoting=csv.QUOTE_ALL)
    writer.writerow([
        "profile_external_code", "job_title", "job_code", "job_family",
        "job_function", "job_level", "template_id",
        "section_type", "section_content", "source_annotation",
    ])
    for section in profile.get("sections", []):
        writer.writerow([
            profile.get("job_code", ""),
            profile.get("job_title", ""),
            profile.get("job_code", ""),
            profile.get("job_family", ""),
            profile.get("job_function", ""),
            profile.get("job_level", ""),
            profile.get("template_id", ""),
            section.get("section_type", ""),
            section.get("content", ""),
            section.get("source", ""),
        ])
    return output.getvalue()


def _build_document(profile: dict[str, Any]) -> str:
    """Format a profile as a clean markdown document."""
    lines = [
        f"# Job Profile: {profile.get('job_title', 'Unknown')}",
        "",
        f"**Job Code:** {profile.get('job_code', 'N/A')}",
        f"**Job Family:** {profile.get('job_family', 'N/A')}",
        f"**Job Function:** {profile.get('job_function', 'N/A')}",
        f"**Job Level:** {profile.get('job_level', 'N/A')}",
        f"**Template:** {profile.get('template_id', 'N/A')}",
        "",
        "---",
    ]
    for section in profile.get("sections", []):
        lines.append(f"\n## {section.get('section_type', 'Section').replace('_', ' ').title()}")
        lines.append(section.get("content", ""))
        lines.append("\n---")

    lines.append("\n*Generated by Job Profile Builder Agent*")
    return "\n".join(lines)


@tool
def deliver_profile_tool(
    profile_json: str,
    output_mode: str,
) -> str:
    """
    Deliver an approved job profile in the selected output mode.

    Args:
        profile_json: JSON string of the approved profile (from generate_profile_tool)
        output_mode: One of 'api_write', 'csv_export', 'document'

    Returns:
        JSON with delivery result, including content or confirmation.
    """
    try:
        profile: dict[str, Any] = json.loads(profile_json)
    except json.JSONDecodeError as e:
        return json.dumps({"error": f"Invalid profile JSON: {e}"})

    job_code = profile.get("job_code", "unknown")

    if output_mode == "api_write":
        # The actual API call is made by the agent via MCP tools.
        # This tool returns the payload for the agent to send.
        payload = {
            "objectType": "JobProfile",
            "externalCode": job_code,
            "jobTitle": profile.get("job_title", ""),
            "jobFamily": profile.get("job_family", ""),
            "jobFunction": profile.get("job_function", ""),
            "jobLevel": profile.get("job_level", ""),
            "templateId": profile.get("template_id", ""),
            "sections": profile.get("sections", []),
        }
        logger.info(
            "M5.achieved: profile delivered — output_mode=api_write, profile_id=%s",
            job_code,
        )
        return json.dumps({
            "mode": "api_write",
            "status": "ready",
            "payload": payload,
            "instruction": "Use the Generic Objects MCP write tool to create this job profile in SuccessFactors with the provided payload.",
            "fallback_note": "If the API write fails, call deliver_profile_tool again with output_mode='csv_export' to preserve the content.",
        })

    elif output_mode == "csv_export":
        csv_content = _build_csv(profile)
        filename = f"{job_code}_job_profile.csv"
        logger.info(
            "M5.achieved: profile delivered — output_mode=csv_export, profile_id=%s",
            job_code,
        )
        return json.dumps({
            "mode": "csv_export",
            "status": "success",
            "filename": filename,
            "content": csv_content,
            "import_note": "Import this CSV into SuccessFactors via Admin Center > Import and Export Data > Job Profile Builder.",
        })

    elif output_mode == "document":
        doc_content = _build_document(profile)
        logger.info(
            "M5.achieved: profile delivered — output_mode=document, profile_id=%s",
            job_code,
        )
        return json.dumps({
            "mode": "document",
            "status": "success",
            "content": doc_content,
        })

    else:
        logger.warning(
            "M5.missed: output delivery failed — output_mode=%s, reason=unknown_mode",
            output_mode,
        )
        return json.dumps({
            "error": f"Unknown output_mode: '{output_mode}'. Use 'api_write', 'csv_export', or 'document'.",
        })
